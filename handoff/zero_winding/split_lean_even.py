"""Split the monolithic list of zero-winding intervals into four Lean files (the single 760-entry file needs more
memory to build than the 7 GB machine has) and write the file that joins them.
usage: split_lean_even.py MONOLITHIC OUTDIR      (OUTDIR = the GaugeGaps source directory)"""
import os, re, sys
from fractions import Fraction as Fr
src, outdir = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8").read().split("\n")
ents = []          # (comment, entry)
for i, l in enumerate(lines):
    if l.startswith("  ⟨"):
        ents.append((lines[i - 1], l.rstrip(",").rstrip()))
        if ents[-1][1].endswith("]"): ents[-1] = (ents[-1][0], ents[-1][1][:-1])
N = len(ents); K = 4; size = -(-N // K)
rat = lambda s: Fr(s.replace(" ", ""))
la = lambda e: rat(re.match(r"\s*⟨([^,]+),([^,]+),", e).group(1)); lb = lambda e: rat(re.match(r"\s*⟨([^,]+),([^,]+),", e).group(2))
q = lambda x: str(x) if x.denominator == 1 else f"({x.numerator} / {x.denominator})"
os.makedirs(os.path.join(outdir, "LadderEven"), exist_ok=True)
open(os.path.join(outdir, "LadderEven", "Defs.lean"), "w").write('''import CertifiedGaps.ChainCheck

/-!
# Zero-winding sector of the SU(2) ladder: intervals with chain certificates (definitions)
-/

open CertifiedGaps

namespace GaugeGaps.LadderEven

/-- A coupling interval with its seed temperature and chain certificate. -/
structure Interval where
  la : ℚ
  lb : ℚ
  β₀ : ℚ
  cert : ChainCertificate

/-- `tilesB l a b`: the intervals of `l` are nondegenerate, the first starts at `a`, each ends where the next starts,
and the last ends at `b` (for the empty list: `a = b`). -/
def tilesB : List Interval → ℚ → ℚ → Bool
  | [], a, b => decide (a = b)
  | I :: l, a, b => decide (I.la = a) && (decide (I.la < I.lb) && tilesB l I.lb b)

theorem tilesB_append {l₁ l₂ : List Interval} {a b c : ℚ} (h₁ : tilesB l₁ a b = true) (h₂ : tilesB l₂ b c = true) :
    tilesB (l₁ ++ l₂) a c = true := by
  induction l₁ generalizing a with
  | nil =>
    have : a = b := by simpa [tilesB] using h₁
    subst this; simpa using h₂
  | cons I l ih =>
    simp only [tilesB, Bool.and_eq_true, decide_eq_true_eq] at h₁
    simp only [List.cons_append, tilesB, Bool.and_eq_true, decide_eq_true_eq]
    exact ⟨h₁.1, h₁.2.1, ih h₁.2.2⟩

/-- A tiling covers every real point between its ends. -/
theorem exists_mem_of_tilesB {l : List Interval} {a b : ℚ} (h : tilesB l a b = true) (hab : a < b) (x : ℝ)
    (hax : (a : ℝ) ≤ x) (hxb : x ≤ (b : ℝ)) : ∃ I ∈ l, (I.la : ℝ) ≤ x ∧ x ≤ (I.lb : ℝ) := by
  induction l generalizing a with
  | nil =>
    have : a = b := by simpa [tilesB] using h
    exact absurd this (ne_of_lt hab)
  | cons I l ih =>
    simp only [tilesB, Bool.and_eq_true, decide_eq_true_eq] at h
    obtain ⟨hIa, hI, hl⟩ := h
    by_cases hx : x ≤ (I.lb : ℝ)
    · exact ⟨I, List.mem_cons_self, by rw [hIa]; exact hax, hx⟩
    · have hx' : (I.lb : ℝ) < x := lt_of_not_ge hx
      have hlt : I.lb < b := by exact_mod_cast lt_of_lt_of_le hx' hxb
      obtain ⟨J, hJ, hJx⟩ := ih hl hlt (le_of_lt hx')
      exact ⟨J, List.mem_cons_of_mem _ hJ, hJx⟩

end GaugeGaps.LadderEven
''')
names = []
for k in range(K):
    part = ents[k * size:(k + 1) * size]
    if not part: continue
    a, b = la(part[0][1]), lb(part[-1][1]); name = f"part{k + 1}"; names.append((name, a, b, len(part)))
    body = ",\n".join(c + "\n" + e for c, e in part)
    open(os.path.join(outdir, "LadderEven", f"Part{k + 1}.lean"), "w").write(f'''import GaugeGaps.LadderEven.Defs

/-! Zero-winding sector, intervals {k * size + 1} to {k * size + len(part)} of {N}: couplings from {a} to {b}. Generated; see `zero_winding/`. -/

open CertifiedGaps

set_option maxRecDepth 1000000

namespace GaugeGaps.LadderEven

def {name} : List Interval := [
{body}]

theorem {name}_length : {name}.length = {len(part)} := by decide +kernel

theorem {name}_valid : ∀ I ∈ {name}, I.cert.Valid := by decide +kernel

theorem {name}_β₀_pos : ∀ I ∈ {name}, 0 < I.β₀ := by decide +kernel

theorem {name}_tiles : tilesB {name} {q(a)} {q(b)} = true := by decide +kernel

end GaugeGaps.LadderEven
''')
LAST = names[-1][2]
imports = "\n".join(f"import GaugeGaps.LadderEven.Part{k + 1}" for k in range(len(names)))
app = " ++ ".join(n for n, *_ in names)
def nest(f):             # proof term for a property of every member of part1 ++ (part2 ++ ...)... written as nested rcases
    return None
valid_cases = "\n".join(f"  · exact {n}_valid I h" for n, *_ in names)
pos_cases = "\n".join(f"  · exact {n}_β₀_pos I h" for n, *_ in names)
pat = "h" + " | h" * (len(names) - 1)
tiles = names[-1][0] + "_tiles"
for n, *_ in reversed(names[:-1]):
    tiles = f"tilesB_append {n}_tiles ({tiles})"
open(os.path.join(outdir, "LadderEvenIntervals.lean"), "w").write(f'''{imports}

/-!
# Zero-winding sector of the SU(2) ladder: chain certificates on a tiling of `[0, {LAST}]`

Generated by `zero_winding/gen_lean_even.py` and `zero_winding/split_lean_even.py`. The {N} intervals live in the
files `LadderEven/Part1` to `Part{len(names)}`; each entry is an interval `[la, lb]` of the coupling `λ`, the seed inverse
temperature `β₀` and a chain certificate whose first entries are upper bounds on the seed defects of that interval
(from `zero_winding/even_seeds.jl`, padded upward by a relative 3e-4). The kernel checks every certificate and that
the intervals tile `[0, {LAST}]`. `gap_at` is upstream's abstract theorem applied to the interval containing a given
coupling: for ANY family of spectra satisfying the spatial moment bounds and the two seed purities of that interval,
the gap on every even ring `L ≥ 2` exceeds `log r / β₀`. The family meant is the spectrum of the ladder Hamiltonian
restricted to the sector `c = +1` of the winding charge. That this family satisfies the hypotheses is the content
of Lemmas 1 to 5 of the note; it is not proved here. The seed inequalities are re-established for every interval by
a second implementation, `zero_winding/even_replay.py`.
-/

open Real CertifiedGaps

namespace GaugeGaps.LadderEven

/-- The {N} intervals, in increasing order. -/
def intervals : List Interval := {app}

theorem intervals_length : intervals.length = {N} := by
  simp [intervals, {", ".join(n + "_length" for n, *_ in names)}]

theorem intervals_valid : ∀ I ∈ intervals, I.cert.Valid := by
  intro I hI
  simp only [intervals, List.mem_append] at hI
  rcases hI with {pat.replace("h | h", "h | h") if len(names) < 3 else "((h | h) | h) | h" if len(names) == 4 else pat}
{valid_cases}

theorem intervals_β₀_pos : ∀ I ∈ intervals, 0 < I.β₀ := by
  intro I hI
  simp only [intervals, List.mem_append] at hI
  rcases hI with {"((h | h) | h) | h" if len(names) == 4 else pat}
{pos_cases}

/-- The intervals tile `[0, {LAST}]`. -/
theorem intervals_tile : tilesB intervals 0 {q(LAST)} = true := by
  have h := {tiles}
  simpa [intervals, List.append_assoc] using h

/-- Every coupling in `[0, {LAST}]` lies in one of the intervals. -/
theorem exists_interval (x : ℝ) (h0 : 0 ≤ x) (h1 : x ≤ {q(LAST)}) : ∃ I ∈ intervals, (I.la : ℝ) ≤ x ∧ x ≤ (I.lb : ℝ) :=
  exists_mem_of_tilesB intervals_tile (by norm_num) x (by exact_mod_cast h0) (by exact_mod_cast h1)

/-- Upstream's abstract theorem on one interval: seeds in, gap out. -/
theorem gap_on_interval {{ι : ℕ → Type*}} [∀ L, Fintype (ι L)] [∀ L, Nonempty (ι L)]
    (E : (L : ℕ) → ι L → ℝ) (hZ : HasSpatialMomentBounds E 2) {{I : Interval}} (hI : I ∈ intervals)
    (hs : 1 - (I.cert.sAt 0 : ℝ) ≤ spatialPurity E 2 I.β₀)
    (ht : 1 - (I.cert.tAt 0 : ℝ) ≤ thermalPurity E (2 * 2) I.β₀) {{L : ℕ}} (hL : 2 ≤ L) (hLe : Even L) :
    GapGT (E L) (log (I.cert.r : ℝ) / I.β₀) :=
  gapGT_of_chainCertificate E (by norm_num) (by decide) (by exact_mod_cast intervals_β₀_pos I hI) hZ
    I.cert (intervals_valid I hI) hs ht hL hLe

end GaugeGaps.LadderEven
''')
print(N, "intervals in", len(names), "parts:", [(n, str(a), str(b), m) for n, a, b, m in names])

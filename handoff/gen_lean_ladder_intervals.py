"""Lean chain certificates for the 240 coupling intervals of the ladder theorem.
For each interval the stored seed defects (padded upward by a relative 1e-4 and rounded up to 9 decimals; the first version used 1e-6, and the independent replay then failed on 2 of 240 intervals by 5e-7 and 6e-6 of the defect, because two valid trial vectors give slopes that differ by up to 3e-8) go through
upstream's lean/scripts/chain_certificate.jl; the Lean file re-checks every certificate in the kernel and states the
gap on each interval as an instance of upstream's abstract theorem. This removes my Python mirror of the recurrence
from the trusted base."""
import json, subprocess, sys
from fractions import Fraction as Fr
from concurrent.futures import ThreadPoolExecutor
JULIA = "/home/claude/julia/julia-1.12.4/bin/julia"; SCRIPT = "/home/claude/ext/CertifiedGaps/code/lean/scripts/chain_certificate.jl"
rows = [r for r in json.load(open("plaq_interval_A.json")) if Fr(r["lb"]) <= 2] + json.load(open("plaq_interval_B.json")) + json.load(open("plaq_interval_C.json"))
rows.sort(key=lambda r: Fr(r["la"])); assert len(rows) == 240
for a, b in zip(rows, rows[1:]): assert Fr(a["lb"]) == Fr(b["la"])
assert Fr(rows[0]["la"]) == 0 and Fr(rows[-1]["lb"]) == 6
def up(x, digits=9):
    f = Fr(10) ** digits; return Fr(int(Fr(x) * (1 + Fr(1, 10**4)) * f) + 1, f)
def one(r):
    s, t, b = up(r["eps_s"]), up(r["eps_t"]), Fr(r["beta0"])
    p = subprocess.run([JULIA, "--project=/home/claude/ext/CertifiedGaps/code/julia", SCRIPT, f"{s.numerator}//{s.denominator}", f"{t.numerator}//{t.denominator}", f"{b.numerator}//{b.denominator}", "8"], capture_output=True, text=True)
    assert p.returncode == 0, p.stderr[-300:]
    lines = p.stdout.strip().split("\n"); return float(lines[0].split("=")[-1]), "\n".join(lines[1:])
with ThreadPoolExecutor(2) as ex: res = list(ex.map(one, rows))
q = lambda x: str(Fr(x)).replace("/", " / ")
entries = []
for r, (bound, body) in zip(rows, res):
    body1 = " ".join(l.strip() + "," for l in body.split("\n")).rstrip(",")
    entries.append(f"  -- [{r['la']}, {r['lb']}]: bound ≈ {bound:.4f} (ball arithmetic: {r['bound_lower']:.4f})\n  ⟨{q(r['la'])}, {q(r['lb'])}, {q(r['beta0'])}, {{ {body1} }}⟩")
